import test from 'node:test';
import assert from 'node:assert/strict';
import * as THREE from 'three';
import { createDeliveryIntro } from '../src/intro.js';

test('room collapses onto the supplied existing land dot before the circle disappears', t => {
  const original = Object.getOwnPropertyDescriptor(globalThis, 'document');
  const context = { fillRect() {}, fillText() {}, beginPath() {}, moveTo() {}, lineTo() {}, quadraticCurveTo() {}, stroke() {}, createRadialGradient: () => ({ addColorStop() {} }) };
  Object.defineProperty(globalThis, 'document', { configurable: true, value: { createElement: () => ({ getContext: () => context }) } });
  t.after(() => original ? Object.defineProperty(globalThis, 'document', original) : delete globalThis.document);
  const world = new THREE.Group(); world.position.x = -.45;
  const point = new THREE.Vector3(.05, .8, 2.1).setLength(2.29368);
  const dots = new THREE.Points(new THREE.BufferGeometry().setFromPoints([point]), new THREE.PointsMaterial({ size: .018 }));
  world.add(new THREE.Group(), dots);
  const camera = new THREE.PerspectiveCamera(38, 16 / 9, .1, 100);
  const offset = new THREE.Vector3(0, .8, 2.1).setLength(8.24);
  const intro = createDeliveryIntro({ camera, world, overviewOffset: offset, surfaceRadius: 2.3256, getDeliveryPoint: () => point, onReveal() {}, onComplete() {}, onCaption() {} });
  intro.start(0);
  const room = world.getObjectByName('delivery-room'), wall = world.getObjectByName('intro-rounding-wall');
  intro.update(4.5);
  assert.equal(wall.morphTargetInfluences[0], 0);
  assert.equal(room.scale.x, .085);
  assert.equal(wall.material.opacity, 1);
  intro.update(6.4);
  assert(room.visible && dots.visible && wall.material.opacity > 0);
  assert(room.position.distanceTo(point) < 1e-9);
  assert.equal(wall.morphTargetInfluences[0], 1);
  const circleCenter = wall.localToWorld(new THREE.Vector3(0, 0, .175));
  const actualDot = world.localToWorld(point.clone());
  assert(circleCenter.distanceTo(actualDot) < 1e-8, 'the circle and existing dot must coincide before handoff');
  assert(Math.abs(room.scale.x * 7.5 - .018 * Math.tan(THREE.MathUtils.degToRad(19))) < 1e-9);
  intro.update(6.9);
  assert(!room.visible && dots.visible);
  assert.equal(dots.geometry.attributes.position.count, 1, 'no extra marker is created');
  intro.finish(); intro.start(10);
  assert.equal(room.scale.x, .085);
  assert.equal(wall.morphTargetInfluences[0], 0);
});
